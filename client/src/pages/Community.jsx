import React, { useCallback, useEffect, useState } from 'react'
import { useAuth, useUser } from '@clerk/clerk-react'
import { Download, ExternalLink, Heart, Sparkles, X } from 'lucide-react'
import axios from 'axios'
import toast from 'react-hot-toast'

axios.defaults.baseURL = import.meta.env.VITE_BASE_URL;

const Community = () => {
  const [creations, setCreations] = useState([])
  const { user } = useUser()
  const [loading, setLoading] = useState(true)
  const [activeModalImage, setActiveModalImage] = useState(null)
  const { getToken } = useAuth()

  const fetchCreations = useCallback(async () => {
    try {
      setLoading(true);
      const token = await getToken();
      const { data } = await axios.get(
        '/api/user/get-published-creations',
        { headers: { Authorization: `Bearer ${token}` } }
      );
      if (data.success) {
        setCreations(data.creations || []);
      } else {
        toast.error(data.message || 'Failed to load creations');
      }
    } catch (error) {
      toast.error(error.response?.data?.message || error.message || 'Failed to fetch community creations');
    } finally {
      setLoading(false);
    }
  }, [getToken]);

  const imageLikeToggle = async (id) => {
    try {
      const token = await getToken();
      const { data } = await axios.post(
        '/api/user/toggle-like-creation',
        { id },
        { headers: { Authorization: `Bearer ${token}` } }
      );
      if (data.success) {
        toast.success(data.message);
        // Optimistic update
        setCreations((prev) =>
          prev.map((c) => {
            if (c.id === id) {
              const likes = Array.isArray(c.likes) ? [...c.likes] : [];
              const uId = user?.id;
              const hasLiked = likes.includes(uId);
              const updatedLikes = hasLiked
                ? likes.filter((l) => l !== uId)
                : [...likes, uId];
              return { ...c, likes: updatedLikes };
            }
            return c;
          })
        );
      } else {
        toast.error(data.message);
      }
    } catch (error) {
      toast.error(error.response?.data?.message || error.message || 'Action failed');
    }
  };

  useEffect(() => {
    if (user) {
      fetchCreations();
    }
  }, [user, fetchCreations]);

  return (
    <div className='flex-1 h-full flex flex-col p-6 sm:p-8 overflow-y-auto'>
      <div className="mb-6 flex flex-col sm:flex-row sm:items-center sm:justify-between gap-4">
        <div>
          <div className="flex items-center gap-2">
            <Sparkles className="w-5 h-5 text-indigo-500" />
            <h1 className="text-2xl font-bold tracking-tight text-slate-900">Community Showcase</h1>
          </div>
          <p className="mt-1 text-sm text-slate-500">
            Explore and appreciate public AI creations generated by the community.
          </p>
        </div>
        <button
          onClick={fetchCreations}
          className="self-start sm:self-auto text-xs font-medium px-4 py-2 rounded-lg border border-gray-200 bg-white hover:bg-gray-50 text-gray-700 transition cursor-pointer"
        >
          Refresh Feed
        </button>
      </div>

      {loading ? (
        <div className="grid grid-cols-1 sm:grid-cols-2 lg:grid-cols-3 gap-5">
          {[1, 2, 3, 4, 5, 6].map((i) => (
            <div key={i} className="h-64 rounded-xl bg-gray-200 animate-pulse"></div>
          ))}
        </div>
      ) : creations.length === 0 ? (
        <div className="flex-1 flex flex-col items-center justify-center py-20 text-center">
          <div className="w-16 h-16 rounded-2xl bg-indigo-50 text-indigo-600 flex items-center justify-center mb-4">
            <Sparkles className="w-8 h-8" />
          </div>
          <h3 className="text-lg font-semibold text-gray-800">No public creations yet</h3>
          <p className="text-sm text-gray-500 mt-1 max-w-sm">
            Be the first to share your AI creations! Toggle "Publish to Community Feed" when generating images.
          </p>
        </div>
      ) : (
        <div className="grid grid-cols-1 sm:grid-cols-2 lg:grid-cols-3 gap-5">
          {creations.map((creation) => {
            const likesCount = Array.isArray(creation.likes) ? creation.likes.length : 0;
            const isLiked = Array.isArray(creation.likes) && user?.id && creation.likes.includes(user.id);

            return (
              <div 
                key={creation.id} 
                className="group relative rounded-xl overflow-hidden border border-gray-200 bg-black/5 shadow-xs hover:shadow-md transition duration-300"
              >
                <img 
                  src={creation.content} 
                  alt={creation.prompt} 
                  className="w-full h-72 object-cover transition-transform duration-500 group-hover:scale-103 cursor-pointer"
                  onClick={() => setActiveModalImage(creation)}
                />
                
                <div className="absolute inset-0 bg-gradient-to-t from-black/85 via-black/20 to-transparent opacity-90 sm:opacity-0 sm:group-hover:opacity-100 transition-opacity duration-200 p-4 flex flex-col justify-between text-white pointer-events-none">
                  <div className="flex justify-end pointer-events-auto">
                    <button
                      onClick={() => setActiveModalImage(creation)}
                      title="Inspect full image"
                      className="p-1.5 rounded-lg bg-black/40 backdrop-blur-sm text-white hover:bg-black/60 transition cursor-pointer"
                    >
                      <ExternalLink className="w-4 h-4" />
                    </button>
                  </div>

                  <div className="flex items-end justify-between gap-3 pointer-events-auto">
                    <p className="text-xs font-medium line-clamp-2 drop-shadow-sm">
                      {creation.prompt}
                    </p>
                    <button 
                      onClick={() => imageLikeToggle(creation.id)} 
                      className="inline-flex items-center gap-1.5 px-2.5 py-1 rounded-full bg-black/50 backdrop-blur-sm hover:bg-black/70 transition cursor-pointer"
                    >
                      <Heart 
                        className={`w-4 h-4 transition-transform active:scale-125 ${
                          isLiked ? 'fill-red-500 text-red-500' : 'text-white'
                        }`} 
                      />
                      <span className="text-xs font-semibold">{likesCount}</span>
                    </button>
                  </div>
                </div>
              </div>
            );
          })}
        </div>
      )}

      {/* Full-view Modal */}
      {activeModalImage && (
        <div 
          className="fixed inset-0 z-50 flex items-center justify-center bg-black/80 backdrop-blur-xs p-4"
          onClick={() => setActiveModalImage(null)}
        >
          <div 
            className="relative max-w-4xl max-h-[90vh] bg-white rounded-2xl overflow-hidden shadow-2xl flex flex-col"
            onClick={(e) => e.stopPropagation()}
          >
            <div className="flex items-center justify-between p-4 border-b border-gray-100">
              <p className="text-sm font-medium text-gray-800 line-clamp-1 pr-4">
                {activeModalImage.prompt}
              </p>
              <div className="flex items-center gap-2">
                <a
                  href={activeModalImage.content}
                  target="_blank"
                  rel="noreferrer"
                  download="aura-community-image.png"
                  className="inline-flex items-center gap-1.5 text-xs font-medium bg-gray-100 text-gray-700 px-3 py-1.5 rounded-lg hover:bg-gray-200 transition"
                >
                  <Download className="w-3.5 h-3.5" /> Download
                </a>
                <button
                  onClick={() => setActiveModalImage(null)}
                  className="p-1 text-gray-500 hover:text-gray-900 rounded-lg transition cursor-pointer"
                >
                  <X className="w-5 h-5" />
                </button>
              </div>
            </div>
            <div className="p-2 bg-black/5 flex items-center justify-center overflow-auto max-h-[75vh]">
              <img 
                src={activeModalImage.content} 
                alt={activeModalImage.prompt} 
                className="max-h-[70vh] w-auto object-contain rounded-lg"
              />
            </div>
          </div>
        </div>
      )}
    </div>
  )
}

export default Community
